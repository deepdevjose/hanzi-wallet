export const COURSE_TEXT = copy;
export type CourseTextKey = keyof typeof copy;

export function courseText(
  key: CourseTextKey,
  params: Readonly<Record<string, string | number>> = {},
): string {
  const localized = copy[key][LOCALES.indexOf(getLocale())] ?? copy[key][0];
  return localized.replace(/\{(\w+)\}/g, (token: string, name: string) =>
    Object.hasOwn(params, name) ? String(params[name]) : token,
  );
}
